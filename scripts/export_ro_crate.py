#!/usr/bin/env python3
"""export_ro_crate.py — F2: export the claim graph as an RO-Crate package.

RO-Crate is a JSON-LD standard for describing scientific data packages with
provenance metadata (see https://www.ro-crate.org). This export makes the
project's claims machine-readable by external systems (SPARQL endpoints,
yProv4ML, nanopublication registries).

Each claim becomes a `schema:CreativeWork` with `citation` links to its
supporting evidence. Evidence nodes that have an artifact pointer become
`schema:Dataset` with `sha256` checksums. The claim graph itself is the
`dataset` resource.

Writes:
  ro_crate.json       — the main RO-Crate file
  ro_crate_manifest.json — sidecar for local inspection
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def _sha256_file(path: Path) -> str | None:
    import hashlib
    if not path.exists():
        return None
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def export(graph: dict, root: Path, out: Path) -> dict:
    nodes = graph.get("nodes", [])
    edges = graph.get("edges", [])

    entries: list[dict] = []

    # @context
    entries.append({
        "@context": {
            "@vocab": "https://schema.org/",
            "ro": "https://w3id.org/ro/",
            "prov": "http://www.w3.org/ns/prov#",
            "sha256": "https://w3id.org/ro/crate-1.1#sha256",
            "identifier": "https://w3id.org/ro/crate-1.1#identifier",
            "hasContent": "https://w3id.org/ro/crate-1.1#hasContent",
        }
    })

    # root dataset (the claim graph itself)
    entries.append({
        "@id": "ro_crate.json",
        "@type": ["CreativeWork", "Dataset"],
        "identifier": "flybrain-connectome-claim-graph",
        "name": "Flybrain Connectome Claim Graph (VRO)",
        "description": (
            "Type-annotated directed claim graph for the flybrain-connectome "
            "Verifiable Research Object (VRO) protocol. Nodes are typed "
            "(claim/evidence/assumption/definition/risk); edges are typed "
            "(supports/contradicts/depends_on/tests). Generated from "
            "research_claims.json + preregistered protocols PR1-PR5."
        ),
        "datePublished": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "publisher": {
            "@type": "Organization",
            "name": "flybrain-connectome project",
            "url": "https://github.com/lm203688/flybrain-connectome"
        },
        "keywords": [
            "verifiable research object", "preregistration", "claim graph",
            "blueprint", "prov", "nanopublication", "adversarial self-verification",
        ],
        "ro:hasContent": {
            "type": "text/plain",
            "value": "Generated by scripts/export_ro_crate.py"
        },
        "hasPart": [{
            "@id": f"{n['id']}.json" if n.get("type") != "claim" else f"claims/{n['id']}.json"
        } for n in nodes]
    })

    # claims
    for n in nodes:
        if n.get("type") == "claim":
            claim_id = n["id"]
            evidence_links = [
                {"@id": e["from"] + ".json"}
                for e in edges
                if e["to"] == claim_id and e["type"] in ("supports", "tests")
            ]
            assumptions = [
                {"@id": e["from"] + ".json"}
                for e in edges
                if e["to"] == claim_id and e["type"] == "depends_on"
            ]
            entry = {
                "@id": f"claims/{claim_id}.json",
                "@type": "CreativeWork",
                "identifier": claim_id,
                "name": n.get("title") or claim_id,
                "description": n.get("statement", ""),
                "dateModified": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            }
            if n.get("verification_level"):
                entry["ro:verificationLevel"] = n["verification_level"]
            if n.get("status"):
                entry["ro:claimStatus"] = n["status"]
            if evidence_links:
                entry["citation"] = evidence_links
            if assumptions:
                entry["dependsOn"] = assumptions
            entries.append(entry)

    # evidence nodes
    for n in nodes:
        if n.get("type") != "evidence":
            continue
        eid = n["id"]
        entry = {
            "@id": f"{eid}.json",
            "@type": "Dataset",
            "identifier": eid,
            "name": eid,
        }
        if n.get("artifact"):
            p = root / n["artifact"]
            entry["url"] = n["artifact"]
            if n["artifact"].endswith((".json", ".csv")) and p.exists():
                entry["sha256"] = _sha256_file(p)
        if n.get("claim"):
            entry["description"] = n["claim"]
        entries.append(entry)

    crate = {
        "@context": entries[0]["@context"],
        "graph": entries[1:],
    }
    manifest = {
        "schema": "ro-crate-1.1",
        "n_entries": len(entries),
        "n_claims": sum(1 for n in nodes if n.get("type") == "claim"),
        "n_evidence": sum(1 for n in nodes if n.get("type") == "evidence"),
        "n_edges": len(edges),
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }

    with open(out / "ro_crate.json", "w", encoding="utf-8") as f:
        json.dump(crate, f, ensure_ascii=False, indent=2)
    with open(out / "ro_crate_manifest.json", "w", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2)

    return manifest


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--graph", default="claim_graph.json")
    ap.add_argument("--out", default="ro_crate/")
    args = ap.parse_args()

    graph_path = ROOT / args.graph
    with open(graph_path, encoding="utf-8") as f:
        graph = json.load(f)

    out = Path(args.out)
    if not out.is_absolute():
        out = ROOT / out
    out.mkdir(parents=True, exist_ok=True)

    manifest = export(graph, ROOT, out)

    print("=" * 60)
    print("RO-Crate export")
    print(f"  entries: {manifest['n_entries']}")
    print(f"  claims: {manifest['n_claims']} evidence: {manifest['n_evidence']} edges: {manifest['n_edges']}")
    print(f"  wrote: {out / 'ro_crate.json'}")
    print(f"  wrote: {out / 'ro_crate_manifest.json'}")
    print("=" * 60)
    return 0


if __name__ == "__main__":
    sys.exit(main())
